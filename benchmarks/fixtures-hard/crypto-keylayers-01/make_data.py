"""make_data — crypto-keylayers-01 数据生成器（确定性，seed 固定）。

维度：**crypto · 多层推导** —— 现有 4 题（输出纪律×2 / 调用图 / 交叉判断）
都没有覆盖的第五个维度。与既有各题的靶子不重复：

  bigscan     一次 grep 命中（输出纪律·易档）
  chunkconcat 过滤后仍超限，必须落盘再处理（输出纪律·硬档）
  obfchain    调用图推理
  brutelog    交叉判断
  本题        **逐级依赖的多阶段链**：每一层的解法只在上一步的产物里
              显形；入口钥匙不能靠任何关键字定位 —— 指纹不在盘上任何
              地方，必须对 25,000 条 record 全量计算 sha256 才能找到。

题面结构（三层嵌套 + 一条平行诱饵链）：

  vault.export（明文头 + 两份 material blob）
    ├─ 真链  L1 blob 钥 = 指纹命中 record 的 priv → L1 明文（L2 的说明书）
    │           └─ L2 blob 钥 = key2a + key2b 拼接 → 最终明文（flag 在 60% 深度）
    └─ 诱饵链 同 owner 第一条 record 的 priv 能完整解开第二份 blob，
                一路通到一个形似 flag 的假 token —— 只有对照头部的
                material-sha256-16 摘要验真才能把它判出去。

  key2a 在 L1 明文里（三行，仅一行是活的——文档写明判据：与 key2b 组合
  解出来开头是 '# layer 3'）；key2b 在 vault.export 尾部标记之后。
  **两半缺一不可。**

难点与防伪同时成立：

1. **指纹不在盘上** —— keyref 是 sha256(pub)[:16]，dump 里不存指纹列，
   grep 任何关键字都到不了那一条 record。语料 4 MB，整读必被截断，
   只能写脚本全量算。
2. **同 owner 诱饵 + 平行假链** —— 目标 owner 名下 4 条 record；owner-grep
   拿第一条（12% 深度的那条）会解开一条**完整的平行链**，产出可提交的
   假 flag —— 错误路径貌似成功，必须按头部摘要验真。断言锁死：诱饵链
   真的通到假 flag、真链真的拒绝它、两份明文摘要不同。
3. **key2a 三选一** —— 文档给出可自验的判据（与 key2b 组合解出来开头是
   '# layer 3'），不靠猜：解错得到乱码，解对得到下一层头。断言锁死两条
   诱饵与 key2b 组合后真的解不开。
4. **key2b 藏在导出尾部** —— 必须意识到要看一个 341 KB 文件的尾巴，
   且拼接口诀（A+B，无分隔）写在 L1 明文里，不靠猜。
5. **语料无关键字** —— 真 flag 的 "flag{" 字面在 dump 与 export 里 0 次，
   明文区段连 "flag" 都不出现（断言）；flag 只存在于两层 xor 之后。

诚实说明：xor-sha256 不是真实世界的强加密，这里考的是**多阶段纪律 +
验真纪律**（每层的钥匙只在上一步的产物里显形；错误路径产出貌似成功的
答案）。scheme 文档全部写在数据里，不靠猜格式——与 chunkconcat 固定
24 字节切块同一取舍：确定性可复现优先于拟真度，因为它要当前后对照的基准。
"""

from __future__ import annotations

import base64
import hashlib
import random
from pathlib import Path

FLAG = "flag{compute_the_fingerprint_not_grep_it}"
SEED = 20260913

N_RECORDS = 25_000
TARGET_OWNER = "svc-vault-sync@vault.internal"
FP_LEN = 16                    # keyref 指纹长度（sha256(pub) 的前 16 hex）

_L1_MARK = b"# layer 2/3"      # L1 明文的头标记（解对了才看得见）
_L3_MARK = b"# layer 3"        # 最终明文的头标记（key2a 判据）
_TAIL_MARK = "### keystore-tail ###"


def _xor(data: bytes, key: bytes) -> bytes:
    return bytes(b ^ key[i % len(key)] for i, b in enumerate(data))


def _keystream(key_ascii: str) -> bytes:
    return hashlib.sha256(key_ascii.encode("ascii")).digest()


def _encrypt(data: bytes, key_ascii: str) -> bytes:
    # xor 对合：encrypt == decrypt
    return _xor(data, _keystream(key_ascii))


def _layer1_doc(live_a: str, dead_as: list[str], l2_blob: str) -> str:
    """L1 明文模板：真链与诱饵链共用同一份说明书（诱饵链必须以假乱真）。"""
    return "\n".join([
        "# layer 2/3",
        "# scheme: xor-sha256-v1 (same as outer header)",
        "# doc: plaintext = xor(ciphertext, cycle(sha256(key_ascii)))",
        "# keyref: split -- key2 = key2a + key2b (ascii concat, no separator)",
        "#   key2a: one of the three lines below is live; test each combined",
        "#          with key2b -- the live pair yields a plaintext beginning",
        "#          with '# layer 3', a wrong one yields garbage",
        f"key2a = {live_a}",
        *(f"key2a = {d}" for d in dead_as),
        "#   key2b: in vault.export, after the marker '### keystore-tail ###'",
        "",
        l2_blob,
    ]) + "\n"


def _material_plaintext(rng: random.Random, n_lines: int, flag_at: int,
                        flag: str) -> str:
    """最终明文：大量无意义审计行，flag 落在 flag_at 行（约 60% 深度）。"""
    words = ["audit", "sync", "rotate", "verify", "checksum", "replica",
             "quota", "session", "lease", "handoff", "digest", "prune"]
    lines: list[str] = ["# layer 3/3 -- vault recovery material, internal use only",
                        "# generated by vault-sync/2.4.1", ""]
    for i in range(n_lines):
        if i == flag_at:
            lines.append(f"recovery/token = {flag}")
            lines.append("# ---- end recovery material ----")
            continue
        w = rng.choice(words)
        lines.append(f"{w}/{i:05d} = {rng.getrandbits(48):012x} "
                     f"{rng.choice(words)}={rng.randint(0, 9999)}")
    return "\n".join(lines) + "\n"


def main() -> None:
    import argparse

    ap = argparse.ArgumentParser(description="生成 crypto-keylayers-01 的语料")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent,
                    help="输出目录（默认 fixture 目录；runner 传 work_dir）")
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    rng = random.Random(SEED)

    # ── keyserver.dump ────────────────────────────────────────────────
    # 目标 record 在 65% 深度；同 owner 诱饵 3 条散在其他深度。
    target_idx = int(N_RECORDS * 0.65)
    decoy_idx = sorted({int(N_RECORDS * 0.12), int(N_RECORDS * 0.40),
                        int(N_RECORDS * 0.88)} - {target_idx})
    assert len(decoy_idx) == 3
    special = {target_idx: "target", **{i: "decoy" for i in decoy_idx}}

    common_owners = [
        "batch-runner@vault.internal", "monitor@vault.internal",
        "archive@vault.internal", "ops-alert@vault.internal",
    ]
    records: list[dict] = []
    for i in range(N_RECORDS):
        kind = special.get(i, "common")
        owner = TARGET_OWNER if kind in ("target", "decoy") else rng.choice(common_owners)
        pub = hashlib.sha256(f"pub:{i}:{rng.getrandbits(64):016x}".encode()).hexdigest()
        priv = hashlib.sha256(f"priv:{i}:{rng.getrandbits(64):016x}".encode()).hexdigest()
        records.append({"id": f"KS-{i:05d}", "owner": owner,
                        "pub": pub, "priv": priv,
                        "status": "active" if rng.random() > 0.08 else "revoked"})
    target = records[target_idx]
    fp16 = hashlib.sha256(target["pub"].encode("ascii")).hexdigest()[:FP_LEN]

    dump = "\n".join(
        f"{r['id']} owner={r['owner']} pub={r['pub']} priv={r['priv']} "
        f"status={r['status']}"
        for r in records
    ) + "\n"

    # ── key2 的两半 ───────────────────────────────────────────────────
    key2a = hashlib.sha256(f"key2a:{SEED}".encode()).hexdigest()[:32]
    key2b = hashlib.sha256(f"key2b:{SEED}".encode()).hexdigest()[:32]
    key2 = key2a + key2b
    dead_a = [hashlib.sha256(f"dead-a{j}:{SEED}".encode()).hexdigest()[:32]
              for j in (1, 2)]

    # ── L3：最终明文（flag 在约 60% 深度）─────────────────────────────
    n_lines = 2400
    flag_at = int(n_lines * 0.6)
    l3_text = _material_plaintext(rng, n_lines, flag_at, FLAG)

    # ── L2 blob = L3 的密文；L1 明文 = L2 的说明书 ────────────────────
    l2_blob = base64.b64encode(
        _encrypt(l3_text.encode("utf-8"), key2)).decode("ascii")
    l1_text = _layer1_doc(key2a, dead_a, l2_blob)

    # ── 平行诱饵链 ────────────────────────────────────────────────────
    # 同 owner 的第一条诱饵 record 能完整解开导出里的第二份 material blob，
    # 一路通到一个形似 flag 的假 token。规则全在数据里（keyref 选 record、
    # material-sha256-16 验真），但"owner-grep 拿第一条"这条捷径会产出
    # **可提交的假答案** —— 想不失败，必须按头部摘要验真。
    decoy_rec = records[decoy_idx[0]]          # 文件序第一条同 owner record
    assert decoy_rec["owner"] == TARGET_OWNER
    decoy_flag = "flag{verify_the_material_digest_first}"
    assert decoy_flag != FLAG
    key2a_d = hashlib.sha256(f"key2a-decoy:{SEED}".encode()).hexdigest()[:32]
    dead_a_d = [hashlib.sha256(f"dead-ad{j}:{SEED}".encode()).hexdigest()[:32]
                for j in (1, 2)]
    rng_d = random.Random(SEED + 1)
    l3d_text = _material_plaintext(rng_d, n_lines, flag_at, decoy_flag)
    l2d_blob = base64.b64encode(
        _encrypt(l3d_text.encode("utf-8"), key2a_d + key2b)).decode("ascii")
    l1d_text = _layer1_doc(key2a_d, dead_a_d, l2d_blob)
    blob_decoy = base64.b64encode(
        _encrypt(l1d_text.encode("utf-8"), decoy_rec["priv"])).decode("ascii")

    # ── L1 blob = L1 明文的密文（钥 = 目标 record 的 priv）────────────
    l1_blob = base64.b64encode(
        _encrypt(l1_text.encode("utf-8"), target["priv"])).decode("ascii")

    material_digest = hashlib.sha256(l3_text.encode("utf-8")).hexdigest()[:16]

    export = "\n".join([
        "# vault-export v3 -- outbound capture",
        "# scheme: xor-sha256-v1",
        "# doc: plaintext = xor(ciphertext, cycle(sha256(key_ascii)))",
        f"# keyref: pub:{fp16}",
        f"#   fp16 = sha256(pub_ascii).hexdigest()[:{FP_LEN}] of the keyserver record",
        "#   note: the fingerprint is NOT stored in keyserver.dump -- compute it",
        f"# material-sha256-16: {material_digest}",
        "#   sha256(final plaintext utf-8).hexdigest()[:16] -- verify before trusting",
        "# layers: 3   # material blob -> L2 blob -> final plaintext",
        "",
        "# material blob:",
        l1_blob,
        "# material blob:",
        blob_decoy,
        _TAIL_MARK,
        f"key2b = {key2b}",
    ]) + "\n"

    (args.out / "keyserver.dump").write_text(dump, encoding="utf-8")
    (args.out / "vault.export").write_text(export, encoding="utf-8")

    # ── 自检（基准自证，不是信任）────────────────────────────────────
    dump_b, export_b = dump.encode(), export.encode()

    # 1) 语料无 flag 泄漏（关键字 grep 无效）——密文是 base64，随机出现
    #    b"flag" 三连字母是可能的（首跑就被这条自检逮住过），真正要锁的是
    #    flag{ 前缀 + 明文区段（头注释、尾部标记区）里连 "flag" 都不出现
    for name, raw in (("keyserver.dump", dump_b), ("vault.export", export_b)):
        assert raw.count(b"flag{") == 0, f"{name} 出现 flag{{ —— 难度归零"
    plain_head = "\n".join(l for l in export.splitlines() if l.startswith("#") or l.startswith(_TAIL_MARK))
    plain_tail = export.split(_TAIL_MARK, 1)[1]
    assert b"flag" not in plain_head.encode() and b"flag" not in plain_tail.encode()

    # 2) 指纹唯一命中 + 目标在 50–80% 深度
    hits = [r for r in records
            if hashlib.sha256(r["pub"].encode("ascii")).hexdigest()[:FP_LEN] == fp16]
    assert len(hits) == 1 and hits[0] is target, "指纹命中不唯一 —— 消歧难度是假的"
    depth = target_idx / N_RECORDS
    assert 0.5 < depth < 0.8, f"目标在 {depth:.0%} 深度 —— 应埋在中后段"

    # 3) 同 owner 诱饵恰好 4 条；除目标外全都解不开**真** blob
    same_owner = [r for r in records if r["owner"] == TARGET_OWNER]
    assert len(same_owner) == 4 and target in same_owner
    body = export.split("\n\n", 1)[1].split(_TAIL_MARK)[0]
    blob_b64s = [l.strip() for l in body.splitlines()
                 if l.strip() and not l.strip().startswith("#")]
    assert len(blob_b64s) == 2, "material blob 应恰有两份（真链 + 平行诱饵链）"
    blob_true_raw = base64.b64decode(blob_b64s[0])
    blob_decoy_raw = base64.b64decode(blob_b64s[1])
    for decoy in same_owner:
        if decoy is target:
            continue
        got = _xor(blob_true_raw, _keystream(decoy["priv"]))
        assert not got.startswith(_L1_MARK), "同 owner 诱饵竟能解开真 blob —— 诱饵是假的"

    # 4) 真链：目标 priv 解开真 blob；诱饵 key2a 解不开 L2；正确的能
    l1_plain = _xor(blob_true_raw, _keystream(target["priv"]))
    assert l1_plain.startswith(_L1_MARK), "目标 priv 解不开真 blob —— 生成器自己错了"
    got = _xor(blob_true_raw, _keystream(decoy_rec["priv"]))
    assert not got.startswith(_L1_MARK), "诱饵 record 竟能解开真 blob —— 平行链搞反了"
    got = _xor(blob_decoy_raw, _keystream(target["priv"]))
    assert not got.startswith(_L1_MARK), "目标 priv 竟能解开诱饵 blob"
    l2_b64 = l1_plain.decode().split("\n\n", 1)[1].strip()
    l2_blob_raw = base64.b64decode(l2_b64)
    for dead in dead_a:
        got = _xor(l2_blob_raw, _keystream(dead + key2b))
        assert not got.startswith(_L3_MARK), "废弃 key2a 竟能解开 L2 —— 三选一是假的"
    l3_text_rt = _xor(l2_blob_raw, _keystream(key2)).decode("utf-8")
    assert l3_text_rt.startswith(_L3_MARK.decode()), "key2 = A+B 解不开 L2 —— 拼接口诀错了"

    # 4b) 诱饵链必须真的"通"：decoy priv 解开诱饵 blob，一路到假 flag，
    #     且摘要验真把它判出去 —— 貌似成功的错误路径才是真难度
    l1d_plain = _xor(blob_decoy_raw, _keystream(decoy_rec["priv"]))
    assert l1d_plain.startswith(_L1_MARK), "诱饵 record 解不开诱饵 blob —— 陷阱是假的"
    l2d_b64 = l1d_plain.decode().split("\n\n", 1)[1].strip()
    l2d_blob_raw = base64.b64decode(l2d_b64)
    l3d_rt = _xor(l2d_blob_raw, _keystream(key2a_d + key2b)).decode("utf-8")
    assert l3d_rt.startswith(_L3_MARK.decode()), "诱饵链解不通 —— 陷阱是假的"
    assert decoy_flag in l3d_rt and FLAG not in l3d_rt
    assert material_digest in export
    assert hashlib.sha256(l3_text_rt.encode("utf-8")).hexdigest()[:16] == material_digest
    assert hashlib.sha256(l3d_rt.encode("utf-8")).hexdigest()[:16] != material_digest, \
        "诱饵明文的摘要竟与真明文相同 —— 验真失效"

    # 5) flag 只在两层之后；且在 >50% 深度
    assert FLAG in l3_text_rt
    flag_line = next(i for i, l in enumerate(l3_text_rt.splitlines())
                     if FLAG in l)
    assert flag_line / l3_text_rt.count("\n") > 0.5, "flag 埋得太浅 —— 别在头尾的纪律失效"
    # 无钥捷径：裸解 export 的 base64 主体得不到 flag
    assert FLAG not in blob_true_raw.decode("latin-1")
    # 诱饵 record 必须是文件序第一条同 owner record（owner-grep 捷径先撞上它）
    first_same_owner = next(r for r in records if r["owner"] == TARGET_OWNER)
    assert first_same_owner is decoy_rec

    # 6) key2b 只在导出尾部标记之后；标记恰好一次；key2b 不在 L1 明文里
    assert export.count(_TAIL_MARK) == 1
    tail = export.split(_TAIL_MARK, 1)[1]
    assert key2b in tail and key2a not in tail
    assert key2b not in l1_plain.decode()
    assert key2a in l1_plain.decode()

    # 7) 体积断言：dump 必须超整读截断线（只能脚本化），export 尾部发现不了猫腻也不行
    assert len(dump_b) > 1_000_000, f"keyserver.dump 仅 {len(dump_b):,} B —— 整读就能看完"
    assert len(export_b) > 100_000, f"vault.export 仅 {len(export_b):,} B —— 缺乏体积压力"
    # priv 无重复（钥匙空间没有捷径碰撞）
    privs = [r["priv"] for r in records]
    assert len(set(privs)) == N_RECORDS

    print(f"keyserver.dump: {len(dump_b):,} bytes, {N_RECORDS:,} records, "
          f"目标 {target['id']} 在 {depth:.0%} 深度, 同 owner 诱饵 3 条")
    print(f"vault.export: {len(export_b):,} bytes, "
          f"L1 明文 {len(l1_plain):,} B, L3 明文 {len(l3_text_rt):,} B")
    print(f"自检 ✓ 指纹唯一、诱饵全哑、平行诱饵链通到假 flag（摘要验真把它判出去）、"
          f"两层之后见 flag（{flag_line} 行 / 60% 深度）、语料 0 次字面 'flag{{'")


if __name__ == "__main__":
    main()
