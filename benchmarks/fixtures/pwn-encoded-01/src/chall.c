
#include <stdio.h>
#include <string.h>
#include <unistd.h>

const unsigned char enc[] = {0x1f, 0x08, 0x1a, 0x2f, 0x34, 0x33, 0x2b, 0x27, 0x2c, 0x2b, 0x32, 0x03, 0x39, 0x32, 0x3f, 0x33, 0x38, 0x39, 0x38, 0x03, 0x2e, 0x33, 0x38, 0x3d, 0x28, 0x3d, 0x21, 0x00};

void win(void) {
    for (const unsigned char *p = enc; *p; ++p) {
        putchar(*p ^ 0x5c);
    }
    putchar('\n');
}

int main(void) {
    char buf[16];
    read(0, buf, 256);
    win();
    return 0;
}
